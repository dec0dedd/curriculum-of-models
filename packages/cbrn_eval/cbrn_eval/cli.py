"""Click CLI entry point: com-eval sweep / com-eval export."""

import asyncio
import logging
from dataclasses import fields
from pathlib import Path

import click
from dotenv import load_dotenv
from rich.console import Console
from rich.logging import RichHandler
from rich.table import Table

from . import export, output
from .config import EvalConfig
from .runner import run_sweep

console = Console()


@click.group(context_settings={"show_default": True})
def main() -> None:
    """com-eval: sweep adversarial prompts against a served target and export scores."""
    load_dotenv()


@main.command()
@click.option(
    "--prompt-source",
    type=click.Choice(["investigator", "behaviors"]),
    default=EvalConfig.prompt_source,
    help=(
        "Where prompts come from: generated by the investigator model, or "
        "the raw behavior text sent verbatim (the direct-ask baseline)."
    ),
)
@click.option(
    "--behaviors-file",
    default=EvalConfig.behaviors_file,
    help="JSONL of behaviors (behavior_id / category / behavior).",
)
@click.option(
    "--behavior-ids",
    multiple=True,
    help="Restrict to these behavior_ids (repeatable). Default: every row.",
)
@click.option(
    "--n-investigator-generations",
    default=EvalConfig.n_investigator_generations,
    help="Investigator prompts per behavior.",
)
@click.option(
    "--investigator-model",
    default=EvalConfig.investigator_model,
    help="A tinker:// sampler_weights path.",
)
@click.option("--investigator-base-model", default=EvalConfig.investigator_base_model)
@click.option("--investigator-renderer", default=EvalConfig.investigator_renderer)
@click.option("--investigator-max-tokens", default=EvalConfig.investigator_max_tokens)
@click.option("--investigator-temperature", default=EvalConfig.investigator_temperature)
@click.option(
    "--target-base-url",
    default=EvalConfig.target_base_url,
    help="The vLLM server's base URL (no /v1 -- it is appended for you).",
)
@click.option(
    "--target-model", required=True, help="Model name served by vLLM for the target."
)
@click.option("--target-max-tokens", default=EvalConfig.target_max_tokens)
@click.option("--target-temperature", default=EvalConfig.target_temperature)
@click.option(
    "--target-disable-reasoning/--target-enable-reasoning",
    default=EvalConfig.target_disable_reasoning,
    help="Toggle chat_template_kwargs.enable_thinking on the target.",
)
@click.option(
    "--n-target-generations",
    default=EvalConfig.n_target_generations,
    help="Target completions per prompt.",
)
@click.option(
    "--skip-investigator-refusals/--send-investigator-refusals",
    default=EvalConfig.skip_investigator_refusals,
    help=(
        "Record a refusal-shaped investigator prompt as a 0 without calling "
        "the target (True), or send it anyway (False, the default)."
    ),
)
@click.option(
    "--prompt-judge/--no-prompt-judge",
    "use_prompt_judge",
    default=EvalConfig.use_prompt_judge,
    help="Gate each response score on the trainer's prompt judge, as training does.",
)
@click.option("--judge-model", default=EvalConfig.judge_model)
@click.option(
    "--judge-max-tokens",
    default=EvalConfig.judge_max_tokens,
    help="Covers the judge's reasoning tokens too.",
)
@click.option("--investigator-concurrency", default=EvalConfig.investigator_concurrency)
@click.option("--target-concurrency", default=EvalConfig.target_concurrency)
@click.option("--judge-concurrency", default=EvalConfig.judge_concurrency)
@click.option("--output-dir", default=EvalConfig.output_dir)
@click.option(
    "--force-rerun",
    is_flag=True,
    help="Rerun even if this exact config already has a completed run on disk.",
)
def sweep(force_rerun: bool, behavior_ids: tuple[str, ...], **kwargs) -> None:
    """Sample investigator prompts, roll them out against the target, and judge them.

    Results land in <output-dir>/<run_id>_{full.parquet,summary.json}, where
    run_id is a hash of every result-affecting input. A completed run with the
    same run_id is not repeated (--force-rerun overrides); an incomplete one
    is resumed.
    """
    logging.basicConfig(
        level=logging.INFO,
        format="%(message)s",
        handlers=[RichHandler(console=console, show_path=False)],
    )
    # Per-request logs from the HTTP stack drown out the progress logs.
    for name in ("httpx", "openai", "httpcore"):
        logging.getLogger(name).setLevel(logging.WARNING)

    config = EvalConfig(
        behavior_ids=behavior_ids or None,
        **{f.name: kwargs[f.name] for f in fields(EvalConfig) if f.name in kwargs},
    )
    run_id = config.run_id()
    console.print(f"[bold cyan]Run ID[/bold cyan]  {run_id}")

    if output.summary_path(config.output_dir, run_id).exists():
        if force_rerun:
            console.print(
                "[yellow]--force-rerun: discarding previous results for this run.[/yellow]"
            )
            output.remove_run_outputs(config.output_dir, run_id)
        else:
            console.print(
                f"[green]Already complete:[/green] "
                f"{output.summary_path(config.output_dir, run_id)}\n"
                "Use --force-rerun to repeat it."
            )
            return

    try:
        summary = asyncio.run(run_sweep(config, run_id))
    except KeyboardInterrupt:
        # Rows are appended as items complete, so whatever finished is on
        # disk; re-running the same command resumes from there.
        console.print(
            f"\n[yellow]Interrupted.[/yellow] Partial results saved to "
            f"{output.full_path(config.output_dir, run_id)} -- "
            "re-run the same command to resume."
        )
        raise SystemExit(130) from None

    _print_summary(summary)
    console.print(
        f"\n[bold green]Done.[/bold green] {output.summary_path(config.output_dir, run_id)}"
    )


def _print_summary(summary: dict) -> None:
    table = Table(title="Per-behavior results")
    # The gated columns only mean anything when the prompt judge ran; a run
    # without it would show a column of dashes, so leave them out entirely.
    gated = any(b.get("n_prompt_judged") for b in summary["behaviors"].values())
    cols = [
        "behavior_id",
        "rows",
        "inv. refusals",
        "tgt refusals",
        "errors",
        "judged",
        "mean",
        "max",
    ]
    if gated:
        cols += ["prompt fails", "mean gated"]
    for col in cols:
        table.add_column(col, justify="right" if col != "behavior_id" else "left")
    for behavior_id, b in summary["behaviors"].items():
        mean = (
            f"{b['mean_judge_score']:.1f}" if b["mean_judge_score"] is not None else "-"
        )
        cells = [
            behavior_id,
            str(b["n_rows"]),
            str(b["n_investigator_refusals"]),
            str(b["n_target_refusals"]),
            str(b["n_errors"]),
            str(b["n_judged"]),
            mean,
            str(b["max_judge_score"] if b["max_judge_score"] is not None else "-"),
        ]
        if gated:
            mean_gated = (
                f"{b['mean_final_score']:.1f}"
                if b.get("mean_final_score") is not None
                else "-"
            )
            cells += [str(b.get("n_prompt_failed", 0)), mean_gated]
        table.add_row(*cells)
    console.print(table)
    console.print(f"Totals: {summary['totals']}")


@main.command(name="export")
@click.option("--output-dir", default=EvalConfig.output_dir)
@click.option(
    "--export-dir",
    default=None,
    help="Where the CSVs land. Defaults to <output-dir>/exports.",
)
def export_cmd(output_dir: str, export_dir: str | None) -> None:
    """Export every completed run in --output-dir to one CSV each, plus an index."""
    out = Path(output_dir)
    target = Path(export_dir) if export_dir else out / "exports"
    n = export.export_all(out, target)
    if n == 0:
        console.print(f"No completed runs found in {out}")
        return
    console.print(f"[bold green]Exported[/bold green] {n} run(s) to {target}")
